object AppTranslations {

    fun forLanguage(lang: AppLanguage): AppStrings = when (lang) {
        AppLanguage.FR -> FR_STRINGS
        AppLanguage.EN -> EN_STRINGS
        AppLanguage.NL -> NL_STRINGS
        AppLanguage.ES -> ES_STRINGS
        AppLanguage.DE -> DE_STRINGS
        AppLanguage.IT -> IT_STRINGS
    }

    fun lateraliteLabel(lat: LateraliteArcher, lang: AppLanguage): String {
        val s = forLanguage(lang)
        return when (lat) {
            LateraliteArcher.DROITIER -> s.rightHanded
            LateraliteArcher.GAUCHER -> s.leftHanded
        }
    }

    fun typeTestLabel(type: TypeTest, lang: AppLanguage): String {
        val s = forLanguage(lang)
        return when (type) {
            TypeTest.FUT_NU -> s.bareShaftTest
            TypeTest.TEST_PAPIER -> s.paperTuneTest
        }
    }

    fun symptomeLabel(symptome: SymptomeVol, lang: AppLanguage): String {
        val s = forLanguage(lang)
        return when (symptome) {
            SymptomeVol.VOL_PROPRE -> s.symptomCleanFlight
            SymptomeVol.MARSouinage -> s.symptomPorpoising
            SymptomeVol.FISHTAILING -> s.symptomFishtailing
            SymptomeVol.CONTACT_FENETRE -> s.symptomContact
            else -> symptome.label
        }
    }

